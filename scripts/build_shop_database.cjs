// 1. Извлечение позиций из Справочника цен
function mapHandbookItem(item, extraDesc = '') {
  const weightStr = item.weight ? `Вес: ${item.weight} фнт.` : '';
  const desc = extraDesc ? `${extraDesc} ${weightStr}`.trim() : (weightStr ? `Справочник цен (${weightStr})` : 'Базовое снаряжение (Справочник цен)');
  return {
    name: item.name,
    price: formatPrice(item.cost, item.currency),
    desc,
    isHandbook: true
  };
}

