/**
 * Класс управления логикой D&D
 */
export class DndEngine {
  constructor() {
    this.currentTier = 2;
    this.dc = 16;
    this.bonus = 3;
    this.mode = 'realtime'; // 'realtime' | 'turnbased'
    this.timeLimit = 35; // в секундах
    this.maxAttempts = 3;
    this.currentChallenge = null;
  }

  setTier(tierNum) {
    this.currentTier = parseInt(tierNum, 10) || 2;
    const preset = TIER_PRESETS[this.currentTier];
    if (preset) {
      this.dc = preset.defaultDC;
      this.timeLimit = preset.timer;
      this.maxAttempts = preset.attempts;
    }
  }

  setDC(val) {
    this.dc = Math.max(5, Math.min(32, parseInt(val, 10)));
  }

  setBonus(val) {
    this.bonus = Math.max(-5, Math.min(15, parseInt(val, 10)));
  }

  setMode(mode) {
    this.mode = mode === 'turnbased' ? 'turnbased' : 'realtime';
  }

  setTimeLimit(sec) {
    this.timeLimit = Math.max(10, Math.min(120, parseInt(sec, 10)));
  }

  setAttempts(count) {
    this.maxAttempts = Math.max(1, Math.min(8, parseInt(count, 10)));
  }

  // Расчет эффективного модификатора сложности с учетом бонуса персонажа
  // Чем выше бонус персонажа относительно DC, тем шире зоны успеха, больше запас прочности и т.д.
  getEffectiveAdvantage() {
    // В D&D стандарт: d20 + bonus vs DC
    // Ожидаемый бросок кубика: DC - bonus. Если <= 10 — преимущество игрока, если >= 16 — высокая сложность
    const targetRoll = this.dc - this.bonus;
    return {
      targetRoll,
      // Множитель ширины зоны успеха: от 0.5 (очень узкая) до 2.2 (широкая)
      toleranceFactor: Math.max(0.45, Math.min(2.2, 1.0 + (this.bonus * 2 - (this.dc - 10)) * 0.05)),
      // Дополнительный запас прочности отмычек/инструментов
      extraDurability: Math.max(0, Math.floor(this.bonus / 3))
    };
  }

  // Генерация случайного испытания для конкретной мини-игры
  generateRandomChallenge(gameType = 'lockpick') {
    const tierData = TIER_PRESETS[this.currentTier] || TIER_PRESETS[2];
    const items = tierData.objects[gameType] || tierData.objects.lockpick;
    const randomItem = items[Math.floor(Math.random() * items.length)];

    // Разброс DC вокруг тира
    const [minDC, maxDC] = tierData.dcRange;
    const randomDC = Math.floor(Math.random() * (maxDC - minDC + 1)) + minDC;
    this.dc = randomDC;

    this.currentChallenge = {
      gameType,
      name: randomItem.name,
      desc: randomItem.desc,
      dc: this.dc,
      tier: this.currentTier,
      tierName: tierData.tierName
    };

    return this.currentChallenge;
  }

  // Расчет градации исхода с подробными последствиями для Мастера
  evaluateOutcome({ success, timeSpent, mistakes, noiseLevel, gameType = 'lockpick' }) {
    const noisePercent = Math.min(100, Math.max(0, Math.round(noiseLevel)));
    const advantage = this.getEffectiveAdvantage();
    const isCriticalSuccess = success && mistakes === 0 && noisePercent <= 15 && timeSpent <= (this.timeLimit * 0.5);
    const isPartialSuccess = success && (mistakes > 0 || noisePercent >= 60 || timeSpent >= this.timeLimit * 0.85);

    let resultType = 'FAILURE';
    let crest = '💀';
    let title = 'Провал испытания!';
    let subtitle = '';
    let narrative = '';
    let toolsLabel = 'Состояние инструментов:';
    let toolsStatus = 'Повреждены';
    let noiseStatus = `${noisePercent}%`;

    // Оценка шума
    if (noisePercent < 25) {
      noiseStatus += ' (Полная тишина)';
    } else if (noisePercent < 60) {
      noiseStatus += ' (Подозрительный шорох / щелчок)';
    } else {
      noiseStatus += ' (ГРОМКИЙ ЗВУК! Внимание стражи)';
    }

    // Метки и статус состояния инструментов/снаряжения для каждого типа игры
    const toolLabelsMap = {
      lockpick: 'Состояние отмычек:',
      trap: 'Инструменты сапёра:',
      runes: 'Эфирный контур:',
      pickpocket: 'Скрытность и маскировка:',
      alchemy: 'Состояние тигля и зелья:'
    };
    toolsLabel = toolLabelsMap[gameType] || 'Состояние инструментов:';

    const trapDmgDice = this.currentTier === 1 ? '2d10' : this.currentTier === 2 ? '4d10' : '8d10';
    const partialTrapDmg = this.currentTier === 1 ? '1d8' : this.currentTier === 2 ? '3d8' : '6d8';

    if (isCriticalSuccess) {
      resultType = 'CRITICAL_SUCCESS';
      crest = '🌟';
      title = 'Критический Триумф!';
      subtitle = 'Испытание пройдено безупречно с филигранным мастерством!';

      if (gameType === 'lockpick') {
        toolsStatus = 'Идеальное (0 сломано)';
        narrative = 'Мастер: Замок поддался бесшумно, как по маслу! Ни единого лишнего шороха. Охрана за дверью ничего не заподозрила. Рекомендуется выдать вдохновение (Inspiration) или скрытый бонус в сундуке!';
      } else if (gameType === 'trap') {
        toolsStatus = 'Все контуры разряжены без повреждений';
        narrative = 'Мастер: Ловушка деактивирована с хирургической точностью! Персонаж сохранил все детонационные капсюли и ценные компоненты ловушки себе как трофей.';
      } else if (gameType === 'runes') {
        toolsStatus = 'Абсолютный эфирный резонанс';
        narrative = 'Мастер: Руническая печать гармонично открылась, наполнив персонажа благословением (+1d4 к следующей проверке характеристик в течение 1 часа).';
      } else if (gameType === 'pickpocket') {
        toolsStatus = 'Полная невидимость (жертва в неведении)';
        narrative = 'Мастер: Филигранная кража! Добыча скользнула в рукав так мягко, что жертва не заметит пропажу вплоть до следующего утра.';
      } else if (gameType === 'alchemy') {
        toolsStatus = 'Кристально чистый эликсир высшего качества';
        narrative = 'Мастер: Зелье сварено с идеальным балансом эссенций! Оно даёт максимальный возможный эффект без броска костей или действует вдвое дольше.';
      }
    } else if (success && !isPartialSuccess) {
      resultType = 'SUCCESS';
      crest = '🏆';
      title = 'Чистый Успех!';
      subtitle = 'Цель успешно достигнута в пределах допустимого риска.';

      if (gameType === 'lockpick') {
        toolsStatus = mistakes === 0 ? 'Без повреждений' : `Потрачено отмычек: ${mistakes}`;
        narrative = 'Мастер: Замок успешно взломан. Партия получает доступ к содержимому, ситуация под полным контролем.';
      } else if (gameType === 'trap') {
        toolsStatus = 'Механизм обезврежен';
        narrative = 'Мастер: Все боевые триггеры ловушки успешно сняты, путь для партии свободен.';
      } else if (gameType === 'runes') {
        toolsStatus = 'Каналы замкнуты, печать снята';
        narrative = 'Мастер: Магический барьер мерцает и гаснет, тайный проход или свиток открыт.';
      } else if (gameType === 'pickpocket') {
        toolsStatus = 'Предмет в руках вора';
        narrative = 'Мастер: Кража удалась, персонаж благополучно отступил обратно в толпу с добычей.';
      } else if (gameType === 'alchemy') {
        toolsStatus = 'Зелье готово к употреблению';
        narrative = 'Мастер: Реакция прошла штатно, состав разлит по склянкам и готов к применению.';
      }
    } else if (isPartialSuccess) {
      resultType = 'PARTIAL_SUCCESS';
      crest = '⚖️';
      title = 'Успех с Осложнением!';
      subtitle = 'Цель достигнута, но партия заплатила определенную цену.';

      if (gameType === 'lockpick') {
        toolsStatus = `Погнуты / сломаны отмычки (${mistakes} шт.)`;
        narrative = 'Мастер: Замок щелкнул и открылся, но последняя отмычка застряла или лопнула со звоном. Ближайший патруль насторожился и направляется проверить источник шума через 1d4 раундов!';
      } else if (gameType === 'trap') {
        toolsStatus = `Инструменты опалены (${mistakes} сбоев)`;
        narrative = `Мастер: Ловушка обезврежена, но остаточный заряд сдетонировал! Персонаж успел отпрыгнуть, но получает часть урона (${partialTrapDmg}) и уровень шума повышен.`;
      } else if (gameType === 'runes') {
        toolsStatus = 'Остаточное искривление эфира';
        narrative = 'Мастер: Печать открылась, но вспышка арканной энергии ослепляет персонажа на 1 минуту или привлекает внимание эфирных созданий.';
      } else if (gameType === 'pickpocket') {
        toolsStatus = 'Подозрение вызвано';
        narrative = 'Мастер: Кошель срезан, но жертва почувствовала прикосновение и оборачивается! Нужна проверка Обмана (Deception) или немедленный побег.';
      } else if (gameType === 'alchemy') {
        toolsStatus = 'Осадок нестабилен';
        narrative = 'Мастер: Зелье сварено, но из-за скачка температуры имеет побочный эффект (например, снижает скорость или окрашивает кожу в цвет зелья).';
      }
    } else {
      // Полный провал
      const isCriticalFail = mistakes >= this.maxAttempts || timeSpent <= 0.1 || noisePercent >= 85;
      if (isCriticalFail) {
        resultType = 'CRITICAL_FAILURE';
        crest = '💥';
        title = 'Катастрофический Провал!';
        subtitle = 'Сработал худший сценарий: тревога или детонация!';

        if (gameType === 'lockpick') {
          toolsStatus = 'Отмычки сломались и намертво застряли';
          narrative = 'Мастер: Механизм намертво заклинило обломками отмычек! Взлом невозможен. Требуется заклинание "Стук" (Knock) или грубая сила Атлетики со штрафом, поднята тревога!';
        } else if (gameType === 'trap') {
          toolsStatus = 'Инструменты уничтожены взрывом';
          narrative = `Мастер: Боевой детонатор сработал! Ловушка взорвалась, нанося ${trapDmgDice} урона всей партии в радиусе 15 футов. Вся цитадель поднята на уши!`;
        } else if (gameType === 'runes') {
          toolsStatus = 'Энергетический коллапс контура';
          narrative = 'Мастер: Защитные руны сдетонировали магическим взрывом! Персонаж отброшен ударной волной, а тревожный глиф оглашает подземелье звуковой сиреной.';
        } else if (gameType === 'pickpocket') {
          toolsStatus = 'Пойман за руку на месте преступления';
          narrative = 'Мастер: Жертва перехватила руку вора железной хваткой! Крик "Держи вора!" оглашает улицу, стража немедленно атакует.';
        } else if (gameType === 'alchemy') {
          toolsStatus = 'Котел разорван на части';
          narrative = 'Мастер: Критический перегрев! Котел взорвался ядовитыми брызгами и едким паром. Все в комнате совершают спасбросок Телосложения против отравления.';
        }
      } else {
        resultType = 'FAILURE';
        crest = '❌';
        title = 'Неудача!';
        subtitle = 'Испытание не увенчалось успехом. Требуется иной подход.';

        if (gameType === 'lockpick') {
          toolsStatus = `Потрачено отмычек: ${mistakes}`;
          narrative = 'Мастер: Замок не поддался, механизм слишком тугой. Персонажи могут попробовать найти ключ, обойти препятствие или выбить дверь.';
        } else if (gameType === 'trap') {
          toolsStatus = 'Механизм заблокирован во взведенном состоянии';
          narrative = 'Мастер: Обезвредить не удалось. Спусковые нити слишком натянуты, дальнейшие манипуляции гарантированно вызовут детонацию.';
        } else if (gameType === 'runes') {
          toolsStatus = 'Контур заблокирован';
          narrative = 'Мастер: Энергия рассеялась, руны потускнели и закрылись защитной коркой. Потребуется короткий отдых для восстановления эфира.';
        } else if (gameType === 'pickpocket') {
          toolsStatus = 'Скрытность потеряна';
          narrative = 'Мастер: Жертва отошла или спрятала кошель под плащ. Момент упущен, повторная попытка невозможна без отвлечения.';
        } else if (gameType === 'alchemy') {
          toolsStatus = 'Состав испорчен';
          narrative = 'Мастер: Зелье расслоилось и остыло в бесполезный ил. Ингредиенты безвозвратно потрачены.';
        }
      }
    }

    return {
      resultType,
      crest,
      title,
      subtitle,
      timeFormatted: `${timeSpent.toFixed(1)} сек`,
      noiseStatus,
      toolsLabel,
      toolsStatus,
      narrative
    };
  }
}

