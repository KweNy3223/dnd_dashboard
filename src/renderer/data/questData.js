export function generateRandomQuest(category = 'any') {
  const chosenCategory = category === 'any' 
    ? Object.keys(QUEST_TEMPLATES)[Math.floor(Math.random() * Object.keys(QUEST_TEMPLATES).length)]
    : category;

  const templates = QUEST_TEMPLATES[chosenCategory] || QUEST_TEMPLATES.hunt;
  const template = templates[Math.floor(Math.random() * templates.length)];
  const client = CLIENT_TYPES[Math.floor(Math.random() * CLIENT_TYPES.length)];
  const reward = REWARD_PRESETS[Math.floor(Math.random() * REWARD_PRESETS.length)];

  // Слухи
  const truth = RUMOR_TABLE.truths[Math.floor(Math.random() * RUMOR_TABLE.truths.length)];
  const halftruth = RUMOR_TABLE.halftruths[Math.floor(Math.random() * RUMOR_TABLE.halftruths.length)];
  const fake = RUMOR_TABLE.fakes[Math.floor(Math.random() * RUMOR_TABLE.fakes.length)];

  return {
    id: `quest_${Date.now()}_${Math.random().toString(36).substr(2, 5)}`,
    category: chosenCategory,
    title: `${template.titlePrefix}: ${template.location.split(' ').slice(0, 2).join(' ')}`,
    client: client.role,
    clientVibe: client.vibe,
    goal: template.goal,
    twist: template.twist,
    location: template.location,
    urgency: template.urgency,
    reward: reward,
    rumors: [
      { type: 'truth', label: 'Достоверный слух', text: truth },
      { type: 'halftruth', label: 'Приукрашенная молва', text: halftruth },
      { type: 'fake', label: 'Пьяная байка', text: fake }
    ]
  };
}
